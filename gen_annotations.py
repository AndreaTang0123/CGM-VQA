# ── evenly distribute questions across graphs ─────────────────────────────────
graphs = [f'G{i:02d}' for i in range(1, 26)]

def even_assign(q_list, per_graph, n_graphs, seed=42):
    """Distribute question IDs evenly; each graph gets per_graph distinct IDs."""
    rng = random.Random(seed)
    ids = [q['question_id'] for q in q_list]
    total = per_graph * n_graphs
    reps, rem = divmod(total, len(ids))
    seq = ids * reps + rng.sample(ids, rem)
    rng.shuffle(seq)
    # ensure each graph gets per_graph *distinct* question IDs
    result = {}
    used = {g: set() for g in graphs}
    pos = 0
    for g in graphs:
        assigned = []
        attempts = list(seq[pos:]) + list(seq[:pos])
        for qid in attempts:
            if qid not in used[g] and len(assigned) < per_graph:
                assigned.append(qid)
                used[g].add(qid)
                if len(assigned) == per_graph:
                    break
        # fallback: fill from remaining ids if needed
        if len(assigned) < per_graph:
            for qid in ids:
                if qid not in used[g]:
                    assigned.append(qid)
                    used[g].add(qid)
                    if len(assigned) == per_graph:
                        break
        result[g] = assigned
        pos = (pos + per_graph) % len(seq)
    return result

yn_assign  = even_assign(yn_qs,  per_graph=2, n_graphs=25, seed=42)
tmp_assign = even_assign(tmp_qs, per_graph=2, n_graphs=25, seed=99)

# ── resolve N/A temporal questions (not applicable to graph) ──────────────────
def get_fallback_temporal(g, exclude, gd, tmp_qs):
    """Find a temporal QID applicable to graph g, not in exclude set."""
    for q in tmp_qs:
        qid = q['question_id']
        if qid in exclude:
            continue
        raw = gd.get(qid)
        if raw and isinstance(raw, tuple) and raw[0] is not None:
            return qid
    return None

